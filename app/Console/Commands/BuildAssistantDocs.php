<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Str;
use ReflectionClass;
use ReflectionMethod;

/**
 * Scans every route, controller, model, DB table, sidebar menu and hand-written doc,
 * then writes the knowledge base used by the in-app AI assistant:
 *   docs/assistant/knowledge.md   (human readable, commit it)
 *   storage/app/assistant/knowledge.json (chunks used for retrieval)
 */
class BuildAssistantDocs extends Command
{
    protected $signature = 'billiq:build-assistant-docs';
    protected $description = 'Scan routes, controllers, models, DB and menus and build the AI assistant knowledge base';

    private array $chunks = [];

    public function handle(): int
    {
        $this->menuChunks();
        $routeCount = $this->routeChunks();
        $modelCount = $this->modelChunks();
        $this->manualDocChunks();

        $md = "# BillIQ Assistant Knowledge Base\n\nAuto-generated by `php artisan billiq:build-assistant-docs` on " . now()->toDateTimeString() . ".\n\n";
        foreach ($this->chunks as $c) {
            $md .= "## [{$c['kind']}] {$c['title']}\n\n{$c['text']}\n\n";
        }
        @mkdir(base_path('docs/assistant'), 0775, true);
        file_put_contents(base_path('docs/assistant/knowledge.md'), $md);

        @mkdir(storage_path('app/assistant'), 0775, true);
        file_put_contents(storage_path('app/assistant/knowledge.json'), json_encode($this->chunks, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES));

        $this->info(count($this->chunks) . " chunks ({$routeCount} routes, {$modelCount} models) written to docs/assistant/knowledge.md");
        return self::SUCCESS;
    }

    private function add(string $kind, string $title, string $text): void
    {
        $this->chunks[] = ['id' => count($this->chunks), 'kind' => $kind, 'title' => $title, 'text' => trim($text)];
    }

    /** Sidebar menu: module -> screen label -> URL, parsed from Layout.vue */
    private function menuChunks(): void
    {
        $file = resource_path('js/Pages/Layout.vue');
        if (!is_file($file)) return;
        $src = file_get_contents($file);
        preg_match_all("/key: '([^']+)',\s*label: '([^']+)'(.*?)(?=\n  \{\n    key:|\n\];)/s", $src, $sections, PREG_SET_ORDER);
        foreach ($sections as $s) {
            preg_match_all("/label: '([^']+)', page: '[^']*', href: routeUrl\('([^']+)', '([^']+)'\)/", $s[3], $items, PREG_SET_ORDER);
            if (!$items) continue;
            $lines = array_map(fn ($i) => "- {$i[1]} → {$i[3]} (route {$i[2]})", $items);
            $this->add('menu', "Sidebar module {$s[2]}", "Module '{$s[2]}' in the left sidebar contains these screens:\n" . implode("\n", $lines));
        }
    }

    private function routeChunks(): int
    {
        $groups = [];
        $count = 0;
        foreach (Route::getRoutes() as $route) {
            $uri = $route->uri();
            if (Str::startsWith($uri, ['_', 'up', 'sanctum', 'storage', 'captcha'])) continue;
            $action = $route->getActionName();
            $controller = $action === 'Closure' ? 'Closure' : (explode('@', $action)[0] ?? 'Closure');
            $groups[class_basename($controller)][] = [
                'methods' => implode('|', array_diff($route->methods(), ['HEAD'])),
                'uri' => '/' . ltrim($uri, '/'),
                'name' => $route->getName(),
                'action' => $action,
                'mw' => implode(',', $route->gatherMiddleware()),
            ];
            $count++;
        }

        foreach ($groups as $name => $routes) {
            $docs = $this->controllerMethodDocs($routes);
            $lines = [];
            foreach ($routes as $r) {
                $method = str_contains($r['action'], '@') ? explode('@', $r['action'])[1] : '';
                $note = $docs[$method] ?? '';
                $lines[] = "- {$r['methods']} {$r['uri']}" . ($r['name'] ? " [{$r['name']}]" : '') . ($method ? " → {$name}::{$method}" : '') . (str_contains($r['mw'], 'auth') ? ' (login required)' : ' (public)') . ($note ? " — {$note}" : '');
            }
            // split large controllers so retrieval stays focused
            foreach (array_chunk($lines, 30) as $i => $part) {
                $this->add('routes', $name . ($i ? ' (part ' . ($i + 1) . ')' : ''), "Controller {$name} handles these routes:\n" . implode("\n", $part));
            }
        }
        return $count;
    }

    /** Doc comment, validated input names, Inertia screen and "Coming Soon" hints per controller action. */
    private function controllerMethodDocs(array $routes): array
    {
        $first = $routes[0]['action'] ?? '';
        $class = str_contains($first, '@') ? explode('@', $first)[0] : null;
        if (!$class || !class_exists($class)) return [];
        $out = [];
        $ref = new ReflectionClass($class);
        foreach ($ref->getMethods(ReflectionMethod::IS_PUBLIC) as $m) {
            if ($m->class !== $class) continue;
            $note = '';
            if ($doc = $m->getDocComment()) {
                $note = trim(preg_replace('/\s*\*\s*/', ' ', trim($doc, "/* \n\r\t")));
            }
            $file = $m->getFileName();
            if ($file && is_file($file)) {
                $lines = array_slice(file($file), $m->getStartLine() - 1, min(80, $m->getEndLine() - $m->getStartLine() + 1));
                $body = implode('', $lines);
                if (preg_match_all("/'([a-z_\.\*]+)'\s*=>\s*'(?:required|nullable|sometimes)/", $body, $mm)) {
                    $note .= ' Inputs: ' . implode(', ', array_slice(array_unique($mm[1]), 0, 25)) . '.';
                }
                if (preg_match("/Inertia::render\('([^']+)'/", $body, $mm)) {
                    $note .= " Screen: {$mm[1]}.";
                }
                if (preg_match("/Coming Soon[^'\"]*/", $body, $mm)) {
                    $note .= ' ' . $mm[0];
                }
            }
            if ($note) $out[$m->getName()] = trim(Str::limit($note, 300));
        }
        return $out;
    }

    private function modelChunks(): int
    {
        $count = 0;
        foreach (glob(app_path('Models/*.php')) as $file) {
            $class = 'App\\Models\\' . basename($file, '.php');
            if (!class_exists($class)) continue;
            try {
                $ref = new ReflectionClass($class);
                if ($ref->isAbstract() || !$ref->isSubclassOf(\Illuminate\Database\Eloquent\Model::class)) continue;
                $model = new $class;
                $table = $model->getTable();
                $text = "Model {$ref->getShortName()} → table `{$table}`.\n";
                if (Schema::hasTable($table)) {
                    $cols = [];
                    foreach (Schema::getColumns($table) as $c) {
                        $cols[] = $c['name'] . ' (' . $c['type_name'] . ($c['nullable'] ? ', null' : '') . ')';
                    }
                    $text .= 'Columns: ' . implode(', ', $cols) . "\n";
                }
                $fill = $model->getFillable();
                if ($fill) $text .= 'Fillable: ' . implode(', ', $fill) . "\n";
                $uses = array_map('class_basename', class_uses($class));
                if ($uses) $text .= 'Traits: ' . implode(', ', $uses) . "\n";
                $rels = [];
                $src = file($file);
                foreach ($ref->getMethods(ReflectionMethod::IS_PUBLIC) as $m) {
                    if ($m->class !== $class || $m->getNumberOfParameters() > 0) continue;
                    $body = implode('', array_slice($src, $m->getStartLine() - 1, $m->getEndLine() - $m->getStartLine() + 1));
                    if (preg_match('/\$this->(hasMany|hasOne|belongsTo|belongsToMany|morphMany|hasManyThrough)\(\s*([A-Za-z\\\\]+)::class/', $body, $mm)) {
                        $rels[] = "{$m->getName()}() {$mm[1]} " . class_basename($mm[2]);
                    } elseif (preg_match('/\$this->(morphTo|belongsTo)\(/', $body, $mm)) {
                        $rels[] = "{$m->getName()}() {$mm[1]}";
                    }
                }
                if ($rels) $text .= 'Relations: ' . implode('; ', $rels) . "\n";
                $this->add('model', $ref->getShortName() . " ({$table})", $text);
                $count++;
            } catch (\Throwable $e) {
                $this->warn("skip {$class}: " . $e->getMessage());
            }
        }
        return $count;
    }

    private function manualDocChunks(): void
    {
        $files = array_merge(glob(base_path('docs/*.md')), [base_path('README.md')]);
        foreach ($files as $f) {
            if (!is_file($f)) continue;
            foreach (preg_split('/^(?=##? )/m', file_get_contents($f)) as $p) {
                $p = trim($p);
                if (strlen($p) < 40) continue;
                foreach (str_split($p, 3500) as $piece) {
                    $this->add('doc', basename($f) . ' — ' . Str::limit(strtok($p, "\n"), 60), $piece);
                }
            }
        }
    }
}
